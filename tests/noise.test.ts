import { describe, expect, test } from 'claude-code/testing'

import { collectNoise, newNoiseCache } from '../hooks/collect'
import { handoffDiff } from '../hooks/ci/investigate'
import { diffSections, generatedRule, isRewriteOnly, markNoise, rewriteCandidates, rewriteVerdicts } from '../hooks/git/noise'
import type { NoiseRule } from '../hooks/packs/types'
import type { FileChange } from '../types'

// A Godot-style pack's noise: the editor's cache folder and build output are generated; scenes and resources are
// rewritten on save with new uids and counters, written the natural way (no leading space).
const RULES: NoiseRule[] = [
  { id: 'godot-cache', glob: '**/.godot/**', kind: 'generated' },
  { id: 'dist', glob: 'dist/**', kind: 'generated' },
  { id: 'scenes', glob: '**/*.{tscn,tres}', kind: 'editor-rewrite', normalize: ['uid="[^"]*"', 'load_steps=\\d+'] },
]
const file = (path: string, code = ' M'): FileChange => ({ path, code, added: 1, removed: 1 })

// A -U0 section for one file, as git writes it with forced a/ and b/ prefixes.
const section = (path: string, hunks: string[][]) =>
  [`diff --git a/${path} b/${path}`, 'index 1111111..2222222 100644', `--- a/${path}`, `+++ b/${path}`, ...hunks.flatMap((h, i) => [`@@ -${i + 1} +${i + 1} @@`, ...h])].join('\n')

describe('reading a diff', () => {
  test('sections by path, with their hunks; a deleted file by its old path; a binary one from its git header', async () => {
    const deleted = ['diff --git a/old.tres b/old.tres', 'deleted file mode 100644', '--- a/old.tres', '+++ /dev/null', '@@ -1 +0,0 @@', '-[resource]'].join('\n')
    const binary = ['diff --git a/art/sigil.png b/art/sigil.png', 'Binary files a/art/sigil.png and b/art/sigil.png differ'].join('\n')
    const diff = [section('atrium/lobby.tscn', [['-a', '+b'], ['-c', '+d']]), deleted, binary, ''].join('\n')
    expect(diffSections(diff, false).map(s => [s.path, s.hunks.length, s.isComplete])).toEqual([
      ['atrium/lobby.tscn', 2, true],
      ['old.tres', 1, true],
      ['art/sigil.png', 0, true],
    ])
  })

  test("a path with a space keeps it (git's tab dropped), a C-quoted one is unquoted, and a cut diff's last section is partial", async () => {
    const spaced = ['diff --git a/atrium/my scene.tscn b/atrium/my scene.tscn', '--- a/atrium/my scene.tscn\t', '+++ b/atrium/my scene.tscn\t', '@@ -1 +1 @@', '-a', '+b'].join('\n')
    const quoted = ['diff --git "a/atrium/say \\"hi\\".tscn" "b/atrium/say \\"hi\\".tscn"', '--- "a/atrium/say \\"hi\\".tscn"', '+++ "b/atrium/say \\"hi\\".tscn"', '@@ -1 +1 @@', '-a', '+b'].join('\n')
    const sections = diffSections([spaced, quoted].join('\n'), true)
    expect(sections.map(s => [s.path, s.isComplete])).toEqual([
      ['atrium/my scene.tscn', true],
      ['atrium/say "hi".tscn', false],
    ])
  })
})

describe('editor rewrites', () => {
  const normalize = RULES[2]!.normalize!

  test('a uid added to the header and load_steps renumbered are only a rewrite; CRLF lines too', async () => {
    expect(isRewriteOnly([['-[gd_scene format=3]', '+[gd_scene format=3 uid="uid://kestrel_a"]']], normalize)).toBe(true)
    expect(isRewriteOnly([['-[gd_scene load_steps=4 format=3]\r', '+[gd_scene load_steps=5 format=3]\r']], normalize)).toBe(true)
    expect(isRewriteOnly([['-[ext_resource type="Script" path="res://atrium/Lobby.cs" id="1_a"]', '+[ext_resource type="Script" uid="uid://kestrel_b" path="res://atrium/Lobby.cs" id="1_a"]']], normalize)).toBe(true)
  })

  test('a changed ext_resource path still shows, even with churn on the same line', async () => {
    const hunk = ['-[ext_resource type="PackedScene" uid="uid://kestrel_c" path="res://atrium/pennant.tscn" id="2_b"]', '+[ext_resource type="PackedScene" uid="uid://kestrel_d" path="res://atrium/crest.tscn" id="2_b"]']
    expect(isRewriteOnly([hunk], normalize)).toBe(false)
  })

  test('a block moved from one hunk to another shows; no hunks (binary, a mode change) is never a rewrite', async () => {
    const moved = [['-[node name="Gauge" type="ProgressBar" parent="."]'], ['+[node name="Gauge" type="ProgressBar" parent="."]']]
    expect(isRewriteOnly(moved, normalize)).toBe(false)
    expect(isRewriteOnly([], normalize)).toBe(false)
  })

  test('a unique_id normalizer folds the ids an editor adds to node headers', async () => {
    const hunk = ['-[node name="Gauge" type="ProgressBar" parent="."]', '+[node name="Gauge" type="ProgressBar" parent="." unique_id=104]']
    expect(isRewriteOnly([hunk], normalize)).toBe(false)
    expect(isRewriteOnly([hunk], [...normalize, 'unique_id=\\d+'])).toBe(true)
  })
})

describe('which files are noise', () => {
  test('generated by path, anywhere a ** glob reaches, and the untracked folder entry git collapses', async () => {
    expect(['.godot/', '.godot/x/y.cfg', 'game/.godot/x.cfg', 'dist/app.js', 'src/app.ts'].map(p => generatedRule(RULES, p)?.id ?? '')).toEqual([
      'godot-cache',
      'godot-cache',
      'godot-cache',
      'dist',
      '',
    ])
  })

  test('rewrite candidates: modified only, staged or not; never added, renamed, conflicted, untracked or generated', async () => {
    const files = [' M', 'M ', 'MM', 'AM', 'RM', 'UU', '??'].map((code, i) => file(`atrium/s${i}.tscn`, code))
    expect(rewriteCandidates([...files, file('dist/a.tscn')], RULES)).toEqual(['atrium/s0.tscn', 'atrium/s1.tscn', 'atrium/s2.tscn'])
  })

  test('marked: generated by path, rewrites by verdict, a conflict never', async () => {
    const files = [file('.godot/'), file('atrium/lobby.tscn'), file('atrium/gazebo.tscn'), file('dist/a.js', 'UU'), file('src/app.ts')]
    expect(markNoise(files, RULES, { 'atrium/lobby.tscn': true, 'atrium/gazebo.tscn': false }).map(f => [f.path, f.noise ?? ''])).toEqual([
      ['.godot/', 'generated'],
      ['atrium/lobby.tscn', 'editor-rewrite'],
      ['atrium/gazebo.tscn', ''],
      ['dist/a.js', ''],
      ['src/app.ts', ''],
    ])
  })

  test('verdicts from one -U0 diff: a whole rewrite-only section is true, a real change or a cut section false', async () => {
    const churn = section('atrium/lobby.tscn', [['-[gd_scene format=3]', '+[gd_scene format=3 uid="uid://kestrel_a"]']])
    const real = section('atrium/gazebo.tscn', [['-[node name="Gauge" parent="."]', '+[node name="Marquee" parent="."]']])
    const cut = section('atrium/crest.tscn', [['-[gd_scene load_steps=2 format=3]', '+[gd_scene load_steps=3 format=3]']])
    expect(rewriteVerdicts([churn, real, cut].join('\n'), true, RULES)).toEqual({ 'atrium/lobby.tscn': true, 'atrium/gazebo.tscn': false, 'atrium/crest.tscn': false })
  })
})

describe('the CI hand-off', () => {
  const app = section('src/app.ts', [['-const a = 1', '+const a = 2']])
  const churn = section('atrium/lobby.tscn', [['-[gd_scene format=3]', '+[gd_scene format=3 uid="uid://kestrel_a"]']])
  const bundle = section('dist/app.js', [['-x', '+' + 'y'.repeat(200)]])

  test('generated and rewrite-only sections are left out and named; the cut is measured after', async () => {
    const out = handoffDiff([app, churn, bundle, ''].join('\n'), RULES, false, 160)
    expect(out.left).toEqual(['atrium/lobby.tscn', 'dist/app.js'])
    expect(out.text).toContain('+const a = 2')
    expect(out.text).not.toContain('kestrel_a')
    expect(out.isCut).toBe(false)
  })

  test("a cut diff: a generated section whose header arrived is still dropped, a partial rewrite kept, and it's marked cut", async () => {
    const partialRewrite = handoffDiff([app, churn].join('\n'), RULES, true, 30_000)
    expect([partialRewrite.left, partialRewrite.text.includes('kestrel_a'), partialRewrite.isCut]).toEqual([[], true, true])
    const partialBundle = handoffDiff([app, bundle].join('\n'), RULES, true, 30_000)
    expect([partialBundle.left, partialBundle.isCut]).toEqual([['dist/app.js'], true])
  })

  test('with no rules the diff is only cut', async () => {
    expect(handoffDiff(app, [], false, 10)).toEqual({ text: app.slice(0, 10), isCut: true, left: [] })
  })
})

describe('the verdict cache', () => {
  // A -U0 diff of whatever candidates are named, with a uid churn for lobby.tscn and nothing for any other file.
  const diffs: string[][] = []
  const exec = async (argv: string[]) => {
    diffs.push(argv)
    const named = argv.filter(a => a.startsWith(':(top,literal)')).map(a => a.slice(':(top,literal)'.length))
    const out = named.includes('atrium/lobby.tscn') ? section('atrium/lobby.tscn', [['-[gd_scene format=3]', '+[gd_scene format=3 uid="uid://kestrel_a"]']]) : ''
    return { exitCode: 0, stdout: out, stderr: '' }
  }
  const files = [file('atrium/lobby.tscn'), file('atrium/gazebo.tscn'), file('src/app.ts'), file('.godot/', '??')]

  test('one -U0 diff names only the candidates; unchanged stamps read no diff again, and a file it had no section for is not asked again', async () => {
    diffs.length = 0
    const cache = newNoiseCache()
    const stamps = { 'atrium/lobby.tscn': '1:10', 'atrium/gazebo.tscn': '1:20' }
    const first = await collectNoise(exec, files, RULES, 'c0ffee', stamps, cache)
    expect(first.map(f => [f.path, f.noise ?? ''])).toEqual([
      ['atrium/lobby.tscn', 'editor-rewrite'],
      ['atrium/gazebo.tscn', ''],
      ['src/app.ts', ''],
      ['.godot/', 'generated'],
    ])
    expect(diffs.map(a => a.slice(-2))).toEqual([[':(top,literal)atrium/lobby.tscn', ':(top,literal)atrium/gazebo.tscn']])
    expect(diffs[0]!.slice(0, 9)).toEqual(['git', 'diff', '--no-color', '--no-ext-diff', '--no-textconv', '--src-prefix=a/', '--dst-prefix=b/', '-U0', 'HEAD'])
    await collectNoise(exec, files, RULES, 'c0ffee', stamps, cache)
    expect(diffs).toHaveLength(1)
    // A file saved again is the only one diffed; a new commit diffs them all.
    await collectNoise(exec, files, RULES, 'c0ffee', { ...stamps, 'atrium/gazebo.tscn': '2:20' }, cache)
    expect(diffs.at(-1)!.slice(-1)).toEqual([':(top,literal)atrium/gazebo.tscn'])
    await collectNoise(exec, files, RULES, 'beef', { ...stamps, 'atrium/gazebo.tscn': '2:20' }, cache)
    expect(diffs.at(-1)!.slice(-2)).toEqual([':(top,literal)atrium/lobby.tscn', ':(top,literal)atrium/gazebo.tscn'])
  })

  test('changed rules start the cache over; without an editor-rewrite rule no diff runs at all', async () => {
    diffs.length = 0
    const cache = newNoiseCache()
    const stamps = { 'atrium/lobby.tscn': '1:10', 'atrium/gazebo.tscn': '1:20' }
    await collectNoise(exec, files, RULES, 'c0ffee', stamps, cache)
    await collectNoise(exec, files, [...RULES.slice(0, 2), { ...RULES[2]!, normalize: ['uid="[^"]*"'] }], 'c0ffee', stamps, cache)
    expect(diffs).toHaveLength(2)
    diffs.length = 0
    const generatedOnly = await collectNoise(exec, files, RULES.slice(0, 2), 'c0ffee', stamps, newNoiseCache())
    expect([diffs.length, generatedOnly.filter(f => f.noise).map(f => f.path)]).toEqual([0, ['.godot/']])
    expect(await collectNoise(exec, files, [], 'c0ffee', stamps, newNoiseCache())).toBe(files)
  })
})
